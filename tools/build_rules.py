def wrap(text, n=30):
    out = ['']
    for word in text.split():
        if out[-1] and len(out[-1]) + 1 + len(word) > n: out.append(word)
        else: out[-1] = (out[-1] + ' ' + word).strip()
    assert len(out) <= 2, text
    return out + [''] * (2 - len(out))
