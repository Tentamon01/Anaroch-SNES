who = ['ODA THE FARMER', 'OLD WILMA', 'SERGEANT BRAM', 'GIDEON THE MERCHANT', 'BROTHER ANSEL', 'MARTA THE INNKEEPER', 'FINN THE BARD']   # (tools/places.py)
roles = {'NR_TALK': 0, 'NR_SHOP': 1, 'NR_APPRAISE': 2}
folk = []
for n_ in who:
    i = defs.index('"%s"' % n_)
    role = re.findall(r'NR_\w+', defs[:i])[-1]
    k = i + len(n_) + 2
    count = int(re.match(r'\s*,\s*(\d+)', defs[k:]).group(1))
    pairs = re.findall(r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}', defs[k:defs.index('{ AREA_', k) if '{ AREA_' in defs[k:] else len(defs)])[:count]
    assert len(pairs) == count, (n_, count, pairs)
    folk.append((n_, roles[role], [textwrap.wrap((a + ' ' + b).upper(), 26) for a, b in pairs]))
ok = set(" 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ/:+-.()>'!%,?")
out = ['; generated by tools/build_rules.py from the N64 version - do not edit']
def table(label, items): out.append(f'{label}: .word ' + ', '.join(items))
table('person_name', [f'pn{i}' for i in range(len(folk))])
table('person_role', [str(f[1]) for f in folk])
table('person_talkn', [str(len(f[2])) for f in folk])
table('person_talk', [f'pt{i}' for i in range(len(folk))])
table('person_prompt', [f'pp{i}' for i in range(len(folk))])
for i, (n_, role, talks) in enumerate(folk):
    out.append(f'pn{i}: .byte "{n_}", 0')
    verb = 'TRADE WITH ' if role == 1 else 'TALK TO '
    prompt = f'A  {n_} IDENTIFIES' if role == 2 else f'A  {verb}{n_}'
    if len(prompt) > 26: prompt = f'A  {verb}' + n_.split(' THE ')[0]          # (rows are cleared from column 3)
    if len(prompt) > 26: prompt = 'A  IDENTIFY'
    assert len(prompt) <= 26, prompt
    out.append(f'pp{i}: .byte "{prompt}", 0')
    refs = []
    for j, lines_ in enumerate(talks):
        assert len(lines_) <= 4 and all(set(t) <= ok for t in lines_), (n_, lines_)
        for q, t in enumerate(lines_): out.append(f'pl{i}_{j}_{q}: .byte "{t}", 0')
        refs += [f'pl{i}_{j}_{q}' if q < len(lines_) else '0' for q in range(4)]
    table(f'pt{i}', refs or ['0'])
open(os.path.join(ROOT, 'src', 'people.inc'), 'w').write('\n'.join(out) + '\n')
print(f'{len(folk)} townspeople')
