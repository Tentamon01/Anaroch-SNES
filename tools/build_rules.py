def table(name, src=data_h):
    m = re.search(r'\b%s\s*(?:\[[^\]]*\]\s*)*=\s*\{' % name, src)
    assert m, name
    i = m.end() - 1
    toks = re.compile(r'\s*(//[^\n]*|\{|\}|,|"(?:[^"\\]|\\.)*"|[A-Za-z_]\w*|-?\d+\.?\d*f?)')
    stack = [[]]
    while True:
        t = toks.match(src, i)
        assert t, (name, src[i:i + 40])
        i = t.end(); t = t.group(1)
        if t.startswith('//') or t == ',': continue
        if t == '{': stack.append([])
        elif t == '}':
            v = stack.pop(); stack[-1].append(v)
            if len(stack) == 1: return v
        elif t[0] == '"': stack[-1].append(t[1:-1])
        elif t[0].isalpha() or t[0] == '_': stack[-1].append(enums[t])
        else:
            t = t.rstrip('f'); stack[-1].append(float(t) if '.' in t else int(t))

