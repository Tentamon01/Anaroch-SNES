def enc4(px):
    o = bytearray(32)
    for y in range(8):
        for x in range(8):
            v = px[y * 8 + x]; bit = 0x80 >> x
            if v & 1: o[y * 2] |= bit
            if v & 2: o[y * 2 + 1] |= bit
            if v & 4: o[16 + y * 2] |= bit
            if v & 8: o[17 + y * 2] |= bit
    return bytes(o)
